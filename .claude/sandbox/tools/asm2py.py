r"""Assemble a MASM source of new patcher code and print it as a Python table for patch_200cc.py.

usage: asm2py.py <source.asm> <NAME> [<file.py>]

Without <file.py> the table goes to stdout; with it, it replaces the lines between
"# >>> NAME" and "# <<< NAME" in that file (tools/patch_200cc.py).

The patcher stays pure Python: it carries the generated table, not the assembler. The source is
one PROC of position-independent code; external routines are EXTERN symbols named X_<hex address>
(`call X_4438D0`, `jmp X_43AAF5`), which become the patcher's own rel32 call / jmp. Data behind
the code starts with the 4 bytes "GEO1" (or any magic given as the source's `; data magic:` line)
and goes out as one data line. ml.exe assembles, dumpbin.exe disassembles the object file, so the
listing text is dumpbin's own; jumps inside the code are printed with "%08X" for the patcher to
fill in with the final address. The table: (offset, hex bytes, listing text, target) with target
None (plain), ("local", offset) or ("ext", address); data lines have text starting with ";".
"""
import os
import re
import struct
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import paths                                        # noqa: E402

LINE = re.compile(r"^  ([0-9A-F]{8}): ((?:[0-9A-F]{2} )+)\s*(.*)$")
BRANCH = re.compile(r"^(j\w+|call|loop\w*)\s+([0-9A-F]{8})$")


def text_section(obj):
    d = open(obj, "rb").read()
    nsec = struct.unpack_from("<H", d, 2)[0]
    opt = struct.unpack_from("<H", d, 16)[0]
    for i in range(nsec):
        h = 20 + opt + 40 * i
        name = d[h:h + 8].rstrip(b"\0")
        size, ptr = struct.unpack_from("<II", d, h + 16)
        if name.startswith(b".text"):
            return d[ptr:ptr + size]
    raise SystemExit("no .text section")


def main():
    src, name = os.path.abspath(sys.argv[1]), sys.argv[2]
    magic = b"GEO1"
    for line in open(src, encoding="utf-8"):
        m = re.match(r";\s*data magic:\s*(\S+)", line)
        if m:
            magic = m.group(1).encode()
    work = os.path.splitext(src)[0]
    obj = work + ".obj"
    ml, dumpbin = paths.msvc_tool("ml.exe"), paths.msvc_tool("dumpbin.exe")
    if not ml or not dumpbin:
        raise SystemExit("needs ml.exe and dumpbin.exe: Visual Studio with the C++ tools (MSVC x86)")
    r = subprocess.run([ml, "/nologo", "/c", "/Fo" + obj, src], capture_output=True, text=True,
                       cwd=os.path.dirname(src))       # INCLUDE files sit next to the source
    if r.returncode:
        raise SystemExit(r.stdout + r.stderr)
    dis = subprocess.run([dumpbin, "/nologo", "/disasm", "/relocations", obj],
                         capture_output=True, text=True).stdout
    raw = text_section(obj)
    os.remove(obj)                                  # a build product, not kept next to the source
    data_at = raw.find(magic)
    if data_at < 0:
        raise SystemExit("data magic %r not found" % magic)
    relocs = {}
    for m in re.finditer(r"^ ([0-9A-F]{8})\s+REL32\s+[0-9A-F]{8}\s+\w+\s+X_([0-9A-F]+)\s*$", dis, re.M):
        relocs[int(m.group(1), 16)] = int(m.group(2), 16)
    insns = []
    publics = {}                                   # "name::" labels: more entry points
    pending = None
    for line in dis.splitlines():
        lm = re.match(r"^(\w+):\s*$", line)
        if lm:
            pending = lm.group(1)
            continue
        m = LINE.match(line)
        if m and pending:
            publics[int(m.group(1), 16)] = pending
            pending = None
        if m:
            off = int(m.group(1), 16)
            if off >= data_at:
                break
            text = m.group(3).strip()
            # in an exe dumpbin prints 32-bit displacements with 8 digits, in an object file not
            text = re.sub(r"\+([0-9A-F]+)h\]", lambda d: "+%sh]" % (d.group(1).zfill(8) if int(d.group(1), 16) > 0x7F else d.group(1)), text)
            insns.append((off, re.sub(r"\s+", " ", text), text))
    rows = []
    for i, (off, norm, text) in enumerate(insns):
        end = insns[i + 1][0] if i + 1 < len(insns) else data_at
        hx = raw[off:end].hex(" ").upper()
        target = None
        ext = [a for r_off, a in relocs.items() if off < r_off < end]
        if ext:
            assert raw[off] in (0xE8, 0xE9) and end - off == 5, (hex(off), text)
            target = ("ext", ext[0])
            text = "call" if raw[off] == 0xE8 else "jmp"
        else:
            b = BRANCH.match(norm)
            if b:
                target = ("local", int(b.group(2), 16))
                text = "%-11s %%08X" % b.group(1)
        assert not any(off < r_off < end for r_off in relocs) or target and target[0] == "ext", hex(off)
        rows.append((off, hx, text, target))
    blob = raw[data_at:]
    unknown = [o for o in relocs if o >= data_at]
    assert not unknown, "relocations in the data"
    out = ["# generated by .claude/sandbox/tools/asm2py.py from %s; do not edit by hand" % os.path.basename(src),
           "%s = (" % name]
    first = True
    for off, hx, text, target in rows:
        if off in publics and not first:
            out.append("    (0x%04X, '', %r, None)," % (off, ":" + publics[off]))
        first = False
        out.append("    (0x%04X, %r, %r, %r)," % (off, hx, text, target))
    for k in range(0, len(blob), 48):
        out.append("    (0x%04X, %r, %r, None)," % (data_at + k, blob[k:k + 48].hex(" ").upper(),
                                                   "; %s data +%d" % (name, k)))
    out.append(")")
    if len(sys.argv) > 3:
        path = sys.argv[3]
        text = open(path, encoding="utf-8").read()
        start, end = "# >>> %s\n" % name, "# <<< %s\n" % name
        i, j = text.index(start) + len(start), text.index(end)
        open(path, "w", encoding="utf-8", newline="\n").write(text[:i] + "\n".join(out) + "\n" + text[j:])
        print("%s: %d instructions, %d data bytes" % (name, len(rows), len(blob)))
    else:
        print("\n".join(out))


if __name__ == "__main__":
    main()
